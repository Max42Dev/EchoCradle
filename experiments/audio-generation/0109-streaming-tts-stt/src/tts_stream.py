"""Streaming TTS harness: speak each sentence as soon as it is complete.

This defines the interface the orchestrator's speech host will implement, and it
runs today with no model installed via the ``null`` engine (which writes silent
WAVs so the *pipeline timing* is still measurable).

Engines
-------
``null``        Silent WAV per sentence. Stdlib only. Measures pipeline overhead.
``piper``       [HEAVY] Piper (MIT, CPU, ~60-110 MB/voice).
``kokoro``      [HEAVY] Kokoro-82M (Apache-2.0, CPU/GPU, ~0.35 GB).
``sherpa``      [HEAVY] sherpa-onnx TTS (Apache-2.0, CPU, C# API available).

The important property is that synthesis is **per sentence**, so audio for
sentence N plays while sentence N+1 is still being generated by the LLM.

Usage
-----
    python tts_stream.py --text "Hello there. How are you?" --engine null
    python tts_stream.py --text-file ..\\sample.txt --engine null --out out\\
"""

from __future__ import annotations

import argparse
import struct
import time
import wave
from collections.abc import Iterator
from pathlib import Path

from sentence_splitter import SentenceSplitter

SAMPLE_RATE = 24_000  # Kokoro/Piper-class output rate; null engine matches it.


def write_silence(path: Path, seconds: float, sample_rate: int = SAMPLE_RATE) -> None:
    """Write a mono 16-bit silent WAV of the given duration."""
    path.parent.mkdir(parents=True, exist_ok=True)
    frames = int(seconds * sample_rate)
    with wave.open(str(path), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(sample_rate)
        wav.writeframes(struct.pack("<h", 0) * frames)


def estimate_duration(text: str, words_per_minute: int = 165) -> float:
    """Rough spoken duration of a sentence, used by the null engine."""
    words = max(1, len(text.split()))
    return words / words_per_minute * 60.0


class NullTtsEngine:
    """Writes silent audio; measures the streaming pipeline without a model."""

    name = "null"

    def __init__(self, out_dir: Path) -> None:
        self._out_dir = out_dir
        self._index = 0

    def synthesize(self, sentence: str) -> tuple[Path, float]:
        """Return (audio_path, duration_seconds) for one sentence."""
        duration = estimate_duration(sentence)
        path = self._out_dir / f"tts_{self._index:03d}.wav"
        self._index += 1
        write_silence(path, duration)
        return path, duration


