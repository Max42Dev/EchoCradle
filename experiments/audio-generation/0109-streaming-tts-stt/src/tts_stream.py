def make_engine(name: str, out_dir: Path) -> object:
    if name == "null":
        return NullTtsEngine(out_dir)
    raise SystemExit(
        f"engine {name!r} is not wired up in this spike; "
        "uncomment its class above and install its package."
    )


def stream_tts(text_chunks: Iterator[str], engine: object, min_chars: int = 8) -> None:
    """Consume an LLM chunk stream and synthesise each sentence as it completes."""
    splitter = SentenceSplitter(min_chars=min_chars)
    start = time.perf_counter()
    first_audio_at: float | None = None
    total_audio = 0.0
    count = 0

    def speak(sentence: str) -> None:
        nonlocal first_audio_at, total_audio, count
        path, duration = engine.synthesize(sentence)  # type: ignore[attr-defined]
        now = time.perf_counter() - start
        if first_audio_at is None:
            first_audio_at = now
        total_audio += duration
        count += 1
        print(f"  [{now:6.3f}s] SPEAK ({duration:4.2f}s audio) -> {path.name}  {sentence!r}")

    for chunk in text_chunks:
        for sentence in splitter.feed(chunk):
            speak(sentence)
    for sentence in splitter.flush():
        speak(sentence)

    elapsed = time.perf_counter() - start
    print("-" * 60)
    print(f"sentences spoken : {count}")
    print(f"time to 1st audio: {first_audio_at:.3f}s" if first_audio_at else "no audio")
    print(f"total audio      : {total_audio:.2f}s")
    print(f"pipeline wall    : {elapsed:.3f}s")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    src = parser.add_mutually_exclusive_group(required=True)
    src.add_argument("--text", help="text to speak")
    src.add_argument("--text-file", type=Path, help="read text from a file")
    parser.add_argument("--engine", default="null",
                        choices=["null", "piper", "kokoro", "sherpa"])
    parser.add_argument("--out", type=Path, default=Path("out"),
                        help="directory for generated WAVs")
    parser.add_argument("--min-chars", type=int, default=8)
    args = parser.parse_args()

    text = args.text if args.text is not None else args.text_file.read_text(encoding="utf-8")
    # Simulate an LLM token stream: word-sized chunks.
    chunks = (word + " " for word in text.split())

    engine = make_engine(args.engine, args.out)
    print(f"engine={args.engine}  out={args.out}")
    print("-" * 60)
    stream_tts(chunks, engine, min_chars=args.min_chars)


if __name__ == "__main__":
    main()
